# 安全求值白名单
_ALLOWED_FUNCS = {"sqrt": math.sqrt, "pi": math.pi, "abs": abs, "round": round, "pow": pow}


def safe_eval_expr(expr, values):
    """仅允许数字、四则、幂与白名单函数，杜绝任意代码执行。"""
    import ast
    import math
    import operator
    consts = {"pi": math.pi, "e": math.e, "g": 9.8}
    ops = {
        ast.Add: operator.add, ast.Sub: operator.sub, ast.Mult: operator.mul,
        ast.Div: operator.truediv, ast.Pow: operator.pow, ast.USub: operator.neg,
        ast.Mod: operator.mod, ast.FloorDiv: operator.floordiv,
    }

    def _ev(node):
        if isinstance(node, ast.Expression):
            return _ev(node.body)
        if isinstance(node, ast.Constant) and isinstance(node.value, (int, float)):
            return node.value
        if isinstance(node, ast.Num):  # 兼容
            return node.n
        if isinstance(node, ast.Name):
            if node.id in values:
                return values[node.id]
            if node.id in consts:
                return consts[node.id]
            raise ValueError(f"缺少变量 {node.id}")
        if isinstance(node, ast.BinOp) and type(node.op) in ops:
            return ops[type(node.op)](_ev(node.left), _ev(node.right))
        if isinstance(node, ast.UnaryOp) and type(node.op) in ops:
            return ops[type(node.op)](_ev(node.operand))
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
            fn = _ALLOWED_FUNCS.get(node.func.id)
            if not fn:
                raise ValueError(f"不允许的函数 {node.func.id}")
            return fn(*[_ev(a) for a in node.args])
        raise ValueError("公式含不允许的表达式")

    tree = ast.parse(expr, mode="eval")
    return _ev(tree)


