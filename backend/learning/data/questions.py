def filter_questions(stage=None, subject=None, qtype=None, difficulty=None):
    out = QUESTIONS
    if stage:
        out = [q for q in out if q["stage"] == stage]
    if subject:
        out = [q for q in out if q["subject"] == subject]
    if qtype:
        out = [q for q in out if q["type"] == qtype]
    if difficulty:
        out = [q for q in out if q["difficulty"] == int(difficulty)]
    return out


